-- 1. Таблица за Пробите (заглавна част)
CREATE TABLE IF NOT EXISTS public.probi (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    name text NOT NULL,                                 -- Име на пробния резолвер (напр. "Проба DC-25-X")
    target_qty numeric DEFAULT 1 NOT NULL,              -- Целева бройка
    status text DEFAULT 'Чернова' NOT NULL,             -- 'Чернова', 'В производство', 'Одобрена', 'Отхвърлена', 'Архивирана'
    launched_at timestamp with time zone,               -- Дата на пускане в цеха
    completed_at timestamp with time zone,              -- Дата на приключване / одобрение
    notes text,                                         -- Бележки и изисквания
    created_by text                                     -- Автор на пробата
);

-- 2. Таблица за Компонентите (децата) на всяка проба
CREATE TABLE IF NOT EXISTS public.probi_components (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    proba_id bigint REFERENCES public.probi(id) ON DELETE CASCADE NOT NULL,
    part_code text NOT NULL,                            -- Код / Наименование на детайла
    part_name text,                                     -- Описание / име
    qty_per_unit numeric DEFAULT 1 NOT NULL,            -- Бройка за 1 резолвер
    is_new boolean DEFAULT false NOT NULL,              -- Дали е нов детайл (несъществуващ в номенклатурата)
    parent_part_code text DEFAULT NULL,                 -- За под-детайли: код на родителския нов детайл
    material_code text,                                 -- Заготовка / суровина от Склад Материали
    material_norm numeric DEFAULT 1,                    -- Разходна норма на заготовката за 1 брой детайл
    custom_routes jsonb DEFAULT '[]'::jsonb             -- Маршрутни карти на детайла: [{ op_num: 10, op_name: "Струговане", machine: "HAAS ST 10" }, ...]
);

-- Добавяне на колоните ако таблицата вече съществува
DO $$ 
BEGIN 
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='probi_components' AND column_name='material_code') THEN
        ALTER TABLE public.probi_components ADD COLUMN material_code text;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='probi_components' AND column_name='material_norm') THEN
        ALTER TABLE public.probi_components ADD COLUMN material_norm numeric DEFAULT 1;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='probi_components' AND column_name='parent_part_code') THEN
        ALTER TABLE public.probi_components ADD COLUMN parent_part_code text DEFAULT NULL;
    END IF;
END $$;

-- 3. Таблица "Склад Проби" (Зона Проби - напълно изолиран от серийния склад inventory)
CREATE TABLE IF NOT EXISTS public.probi_inventory (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proba_id bigint REFERENCES public.probi(id) ON DELETE CASCADE,
    part_code text NOT NULL,
    operation text NOT NULL,
    quantity numeric DEFAULT 0 NOT NULL,
    updated_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Индекси за бързо търсене
CREATE INDEX IF NOT EXISTS idx_probi_status ON public.probi(status);
CREATE INDEX IF NOT EXISTS idx_probi_components_proba_id ON public.probi_components(proba_id);
CREATE INDEX IF NOT EXISTS idx_probi_components_parent ON public.probi_components(parent_part_code);
CREATE INDEX IF NOT EXISTS idx_probi_inventory_main ON public.probi_inventory(proba_id, part_code, operation);

-- RLS Политики
ALTER TABLE public.probi ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.probi_components ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.probi_inventory ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all on probi" ON public.probi;
CREATE POLICY "Allow all on probi" ON public.probi FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all on probi_components" ON public.probi_components;
CREATE POLICY "Allow all on probi_components" ON public.probi_components FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all on probi_inventory" ON public.probi_inventory;
CREATE POLICY "Allow all on probi_inventory" ON public.probi_inventory FOR ALL USING (true) WITH CHECK (true);

GRANT ALL ON public.probi TO anon, authenticated;
GRANT ALL ON public.probi_components TO anon, authenticated;
GRANT ALL ON public.probi_inventory TO anon, authenticated;

-- ==============================================================
-- 4. ТРИГЕРИ ЗА СКЛАД И ИНВЕНТАР
-- 🟢 Суровините се изписват от "Склад Материали" (таблица sklad)
-- 🟣 Пробните полуфабрикати отиват в "Склад Проби" (probi_inventory),
--    като серийният склад (inventory) остава 100% чист!
-- ==============================================================

CREATE OR REPLACE FUNCTION public.process_inventory_on_otchet()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    new_detail text := LOWER(TRIM(NEW."ID Детайл"));
    new_op text := LOWER(TRIM(NEW."Операция"));
    new_qty numeric := COALESCE(NEW."Количество", 0);
    new_operator text := COALESCE(NEW."Оператор", '');
    new_status text := LOWER(TRIM(NEW."Статус"));
    prev_op text;
    child_record RECORD;
    is_last_op boolean := false;
    is_proba boolean := (NEW."ID План" ILIKE 'PROBA_%');
    p_id bigint := CASE WHEN is_proba THEN CAST(NULLIF(SUBSTRING(NEW."ID План" FROM 7), '') AS bigint) ELSE NULL END;
BEGIN
    IF new_qty = 0 THEN RETURN NEW; END IF;
    IF new_operator ILIKE '%СИСТЕМА (Корекция%' THEN RETURN NEW; END IF;
    IF new_op ILIKE 'Опаковане%' THEN RETURN NEW; END IF;

    IF new_op ILIKE 'Експедиция%' THEN
        IF NOT is_proba THEN
            UPDATE public.inventory SET "Количество" = GREATEST(0, COALESCE("Количество"::text, '0')::numeric - new_qty) WHERE LOWER(TRIM("ID Детайл")) = new_detail AND LOWER(TRIM("Операция")) = 'готов продукт';
        END IF;
        RETURN NEW;
    END IF;

    -- Намиране на предишната операция от marshruti
    SELECT LOWER(TRIM("Име на операция")) INTO prev_op
    FROM public.marshruti 
    WHERE LOWER(TRIM("Код на детайла")) = new_detail 
      AND CAST(NULLIF("№ Операция"::text, '') AS integer) < (
          SELECT CAST(NULLIF("№ Операция"::text, '') AS integer) 
          FROM public.marshruti 
          WHERE LOWER(TRIM("Код на детайла")) = new_detail 
            AND LOWER(TRIM("Име на операция")) = new_op 
          ORDER BY CAST(NULLIF("№ Операция"::text, '') AS integer) DESC 
          LIMIT 1
      )
    ORDER BY CAST(NULLIF("№ Операция"::text, '') AS integer) DESC 
    LIMIT 1;

    -- Проверка дали е последна операция
    SELECT NOT EXISTS (
        SELECT 1 FROM public.marshruti WHERE LOWER(TRIM("Код на детайла")) = new_detail AND CAST(NULLIF("№ Операция"::text, '') AS integer) > (
              SELECT CAST(NULLIF("№ Операция"::text, '') AS integer) FROM public.marshruti WHERE LOWER(TRIM("Код на детайла")) = new_detail AND LOWER(TRIM("Име на операция")) = new_op ORDER BY CAST(NULLIF("№ Операция"::text, '') AS integer) DESC LIMIT 1
          )
    ) INTO is_last_op;

    -- Стъпка 1: Вадим от предходна операция (или от Склад Материали за 1-ва операция)
    IF new_operator NOT ILIKE '%СИСТЕМА%' THEN
        IF prev_op IS NOT NULL THEN
            IF is_proba THEN
                UPDATE public.probi_inventory 
                SET quantity = GREATEST(0, quantity - new_qty), updated_at = now()
                WHERE proba_id = p_id AND LOWER(TRIM(part_code)) = new_detail AND LOWER(TRIM(operation)) = prev_op;
            ELSE
                UPDATE public.inventory SET "Количество" = GREATEST(0, COALESCE("Количество"::text, '0')::numeric - new_qty) WHERE LOWER(TRIM("ID Детайл")) = new_detail AND LOWER(TRIM("Операция")) = prev_op;
            END IF;
        ELSE
            -- 🟢 ПЪРВА ОПЕРАЦИЯ: Взима заготовка/суровина от Склад Материали (за ВСИЧКИ, вкл. ПРОБИ)!
            DECLARE
                nom_mat text;
                nom_qty numeric;
                nom_type text;
            BEGIN
                -- 1) Търсим в Номенклатура
                SELECT LOWER(TRIM("ID Родител")), COALESCE(NULLIF("Разходна норма"::text, ''), '1')::numeric INTO nom_mat, nom_qty
                FROM public."Номенклатура"
                WHERE LOWER(TRIM("ID Детайл")) = new_detail;
                
                -- 2) Ако детайлът е нов пробен, търсим материала му в probi_components
                IF nom_mat IS NULL THEN
                    SELECT LOWER(TRIM(material_code)), COALESCE(NULLIF(material_norm::text, ''), '1')::numeric INTO nom_mat, nom_qty
                    FROM public.probi_components
                    WHERE LOWER(TRIM(part_code)) = new_detail
                    LIMIT 1;
                END IF;

                IF nom_mat IS NOT NULL AND nom_mat != '' THEN
                    SELECT LOWER(TRIM("Тип")) INTO nom_type FROM public."Номенклатура" WHERE LOWER(TRIM("ID Детайл")) = nom_mat;
                    
                    -- Увеличаваме "Изразходено" и намаляваме "Остатък" в Склад Материали!
                    IF nom_type IS NOT NULL AND nom_type ILIKE '%материал%' THEN
                        UPDATE public.sklad 
                        SET "Изразходено" = (COALESCE(NULLIF("Изразходено"::text, ''), '0')::numeric + (new_qty * nom_qty))::text,
                            "Остатък" = GREATEST(0, COALESCE("Остатък", 0) - (new_qty * nom_qty))
                        WHERE LOWER(TRIM("ID Детайл")) = nom_mat;
                    ELSE
                        -- Полуфабрикат
                        IF is_proba THEN
                            UPDATE public.probi_inventory 
                            SET quantity = GREATEST(0, quantity - (new_qty * nom_qty)), updated_at = now()
                            WHERE proba_id = p_id AND LOWER(TRIM(part_code)) = nom_mat AND LOWER(TRIM(operation)) = 'готов продукт';
                        ELSE
                            UPDATE public.inventory 
                            SET "Количество" = GREATEST(0, COALESCE("Количество"::text, '0')::numeric - (new_qty * nom_qty)) 
                            WHERE LOWER(TRIM("ID Детайл")) = nom_mat AND LOWER(TRIM("Операция")) = 'готов продукт';
                        END IF;
                    END IF;
                END IF;
            END;
        END IF;
    END IF;

    -- Стъпка 2: Добавяме в текущата операция
    IF new_status = 'отчетено' THEN
        DECLARE
            target_op text := CASE WHEN is_last_op THEN 'готов продукт' ELSE new_op END;
        BEGIN
            IF is_proba THEN
                UPDATE public.probi_inventory 
                SET quantity = quantity + new_qty, updated_at = now()
                WHERE proba_id = p_id AND LOWER(TRIM(part_code)) = new_detail AND LOWER(TRIM(operation)) = target_op;
                
                IF NOT FOUND THEN
                    INSERT INTO public.probi_inventory (proba_id, part_code, operation, quantity)
                    VALUES (p_id, NEW."ID Детайл", target_op, new_qty);
                END IF;
            ELSE
                UPDATE public.inventory 
                SET "Количество" = COALESCE("Количество"::text, '0')::numeric + new_qty 
                WHERE LOWER(TRIM("ID Детайл")) = new_detail AND LOWER(TRIM("Операция")) = target_op;
                
                IF NOT FOUND THEN
                    INSERT INTO public.inventory ("ID Детайл", "Операция", "Количество") 
                    VALUES (NEW."ID Детайл", target_op, new_qty);
                END IF;
            END IF;
        END;
    END IF;

    RETURN NEW;
END;
$$;

-- Същото при изтриване на отчет (връщане на материал и корекция):
CREATE OR REPLACE FUNCTION public.process_inventory_on_delete_otchet()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    old_detail text := LOWER(TRIM(OLD."ID Детайл"));
    old_op text := LOWER(TRIM(OLD."Операция"));
    old_qty numeric := COALESCE(OLD."Количество", 0);
    old_operator text := COALESCE(OLD."Оператор", '');
    old_status text := LOWER(TRIM(OLD."Статус"));
    prev_op text;
    child_record RECORD;
    is_last_op boolean := false;
    is_proba boolean := (OLD."ID План" ILIKE 'PROBA_%');
    p_id bigint := CASE WHEN is_proba THEN CAST(NULLIF(SUBSTRING(OLD."ID План" FROM 7), '') AS bigint) ELSE NULL END;
BEGIN
    IF old_qty = 0 THEN RETURN OLD; END IF;
    IF old_operator ILIKE '%СИСТЕМА%' THEN RETURN OLD; END IF;
    IF old_op ILIKE 'Опаковане%' THEN RETURN OLD; END IF;

    IF old_op ILIKE 'Експедиция%' THEN
        IF NOT is_proba THEN
            UPDATE public.inventory SET "Количество" = COALESCE("Количество"::text, '0')::numeric + old_qty WHERE LOWER(TRIM("ID Детайл")) = old_detail AND LOWER(TRIM("Операция")) = 'готов продукт';
        END IF;
        RETURN OLD;
    END IF;

    SELECT LOWER(TRIM("Име на операция")) INTO prev_op
    FROM public.marshruti 
    WHERE LOWER(TRIM("Код на детайла")) = old_detail 
      AND CAST(NULLIF("№ Операция"::text, '') AS integer) < (
          SELECT CAST(NULLIF("№ Операция"::text, '') AS integer) 
          FROM public.marshruti 
          WHERE LOWER(TRIM("Код на детайла")) = old_detail 
            AND LOWER(TRIM("Име на операция")) = old_op 
          ORDER BY CAST(NULLIF("№ Операция"::text, '') AS integer) DESC 
          LIMIT 1
      )
    ORDER BY CAST(NULLIF("№ Операция"::text, '') AS integer) DESC 
    LIMIT 1;

    SELECT NOT EXISTS (
        SELECT 1 FROM public.marshruti WHERE LOWER(TRIM("Код на детайла")) = old_detail AND CAST(NULLIF("№ Операция"::text, '') AS integer) > (
              SELECT CAST(NULLIF("№ Операция"::text, '') AS integer) FROM public.marshruti WHERE LOWER(TRIM("Код на детайла")) = old_detail AND LOWER(TRIM("Име на операция")) = old_op ORDER BY CAST(NULLIF("№ Операция"::text, '') AS integer) DESC LIMIT 1
          )
    ) INTO is_last_op;

    -- Вадим от текущата операция
    IF old_status = 'отчетено' THEN
        DECLARE
            target_op text := CASE WHEN is_last_op THEN 'готов продукт' ELSE old_op END;
        BEGIN
            IF is_proba THEN
                UPDATE public.probi_inventory 
                SET quantity = GREATEST(0, quantity - old_qty), updated_at = now()
                WHERE proba_id = p_id AND LOWER(TRIM(part_code)) = old_detail AND LOWER(TRIM(operation)) = target_op;
            ELSE
                UPDATE public.inventory 
                SET "Количество" = GREATEST(0, COALESCE("Количество"::text, '0')::numeric - old_qty) 
                WHERE LOWER(TRIM("ID Детайл")) = old_detail AND LOWER(TRIM("Операция")) = target_op;
            END IF;
        END;
    END IF;

    -- Връщаме в предходната операция (или в Склад Материали)
    IF old_operator NOT ILIKE '%СИСТЕМА%' THEN
        IF prev_op IS NOT NULL THEN
            IF is_proba THEN
                UPDATE public.probi_inventory 
                SET quantity = quantity + old_qty, updated_at = now()
                WHERE proba_id = p_id AND LOWER(TRIM(part_code)) = old_detail AND LOWER(TRIM(operation)) = prev_op;
                
                IF NOT FOUND THEN
                    INSERT INTO public.probi_inventory (proba_id, part_code, operation, quantity)
                    VALUES (p_id, OLD."ID Детайл", prev_op, old_qty);
                END IF;
            ELSE
                UPDATE public.inventory SET "Количество" = COALESCE("Количество"::text, '0')::numeric + old_qty WHERE LOWER(TRIM("ID Детайл")) = old_detail AND LOWER(TRIM("Операция")) = prev_op;
                IF NOT FOUND THEN
                    INSERT INTO public.inventory ("ID Детайл", "Операция", "Количество") VALUES (OLD."ID Детайл", prev_op, old_qty);
                END IF;
            END IF;
        ELSE
            -- 🟢 ВРЪЩАНЕ НА МАТЕРИАЛА В СКЛАД МАТЕРИАЛИ:
            DECLARE
                nom_mat text;
                nom_qty numeric;
                nom_type text;
            BEGIN
                SELECT LOWER(TRIM("ID Родител")), COALESCE(NULLIF("Разходна норма"::text, ''), '1')::numeric INTO nom_mat, nom_qty
                FROM public."Номенклатура"
                WHERE LOWER(TRIM("ID Детайл")) = old_detail;
                
                IF nom_mat IS NULL THEN
                    SELECT LOWER(TRIM(material_code)), COALESCE(NULLIF(material_norm::text, ''), '1')::numeric INTO nom_mat, nom_qty
                    FROM public.probi_components
                    WHERE LOWER(TRIM(part_code)) = old_detail
                    LIMIT 1;
                END IF;

                IF nom_mat IS NOT NULL AND nom_mat != '' THEN
                    SELECT LOWER(TRIM("Тип")) INTO nom_type FROM public."Номенклатура" WHERE LOWER(TRIM("ID Детайл")) = nom_mat;
                    
                    IF nom_type IS NOT NULL AND nom_type ILIKE '%материал%' THEN
                        UPDATE public.sklad 
                        SET "Изразходено" = GREATEST(0, (COALESCE(NULLIF("Изразходено"::text, ''), '0')::numeric - (old_qty * nom_qty)))::text,
                            "Остатък" = COALESCE("Остатък", 0) + (old_qty * nom_qty)
                        WHERE LOWER(TRIM("ID Детайл")) = nom_mat;
                    ELSE
                        IF is_proba THEN
                            UPDATE public.probi_inventory 
                            SET quantity = quantity + (old_qty * nom_qty), updated_at = now()
                            WHERE proba_id = p_id AND LOWER(TRIM(part_code)) = nom_mat AND LOWER(TRIM(operation)) = 'готов продукт';
                            IF NOT FOUND THEN
                                INSERT INTO public.probi_inventory (proba_id, part_code, operation, quantity)
                                VALUES (p_id, nom_mat, 'готов продукт', (old_qty * nom_qty));
                            END IF;
                        ELSE
                            UPDATE public.inventory 
                            SET "Количество" = COALESCE("Количество"::text, '0')::numeric + (old_qty * nom_qty) 
                            WHERE LOWER(TRIM("ID Детайл")) = nom_mat AND LOWER(TRIM("Операция")) = 'готов продукт';
                            IF NOT FOUND THEN
                                INSERT INTO public.inventory ("ID Детайл", "Операция", "Количество") VALUES (nom_mat, 'готов продукт', (old_qty * nom_qty));
                            END IF;
                        END IF;
                    END IF;
                END IF;
            END;
        END IF;
    END IF;

    RETURN OLD;
END;
$$;

