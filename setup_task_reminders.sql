-- ==============================================================================
-- СИСТЕМА ЗА БЛОКИРАЩИ НАПОМНЯНИЯ ЗА НЕПОЕТА ЗАДАЧА (TASK REMINDERS)
-- ==============================================================================

-- 1. Таблица за регистър на напомнянията
CREATE TABLE IF NOT EXISTS public.task_reminders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    reminder_date DATE NOT NULL DEFAULT CURRENT_DATE,
    worker_name TEXT NOT NULL,
    worker_email TEXT NOT NULL,
    machine TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'SENT', -- 'SENT' (изпратено/непрочетено), 'READ' (потвърдено от работника), 'CLAIMED' (поета задача)
    sent_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    read_at TIMESTAMP WITH TIME ZONE,
    claimed_at TIMESTAMP WITH TIME ZONE,
    available_blue_tasks INT DEFAULT 0,
    notes TEXT,
    CONSTRAINT uq_task_reminders_date_worker UNIQUE (reminder_date, worker_email)
);

-- 2. Таблица за актуално работно място (машина) на всеки работник
CREATE TABLE IF NOT EXISTS public.worker_machines (
    worker_email TEXT PRIMARY KEY,
    worker_name TEXT,
    machine TEXT NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Индекси за бързо търсене
CREATE INDEX IF NOT EXISTS idx_task_reminders_date ON public.task_reminders (reminder_date);
CREATE INDEX IF NOT EXISTS idx_task_reminders_worker_date ON public.task_reminders (worker_email, reminder_date);
CREATE INDEX IF NOT EXISTS idx_task_reminders_status ON public.task_reminders (status);

-- Активиране на Supabase Realtime
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'task_reminders'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.task_reminders;
    END IF;
EXCEPTION WHEN OTHERS THEN
    NULL;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'worker_machines'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.worker_machines;
    END IF;
EXCEPTION WHEN OTHERS THEN
    NULL;
END $$;

-- RLS Политики
ALTER TABLE public.task_reminders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.worker_machines ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read task_reminders" ON public.task_reminders;
CREATE POLICY "Allow public read task_reminders" ON public.task_reminders FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Allow public insert task_reminders" ON public.task_reminders;
CREATE POLICY "Allow public insert task_reminders" ON public.task_reminders FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update task_reminders" ON public.task_reminders;
CREATE POLICY "Allow public update task_reminders" ON public.task_reminders FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public delete task_reminders" ON public.task_reminders;
CREATE POLICY "Allow public delete task_reminders" ON public.task_reminders FOR DELETE TO anon, authenticated USING (true);

-- За worker_machines
DROP POLICY IF EXISTS "Allow public read worker_machines" ON public.worker_machines;
CREATE POLICY "Allow public read worker_machines" ON public.worker_machines FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Allow public insert worker_machines" ON public.worker_machines;
CREATE POLICY "Allow public insert worker_machines" ON public.worker_machines FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update worker_machines" ON public.worker_machines;
CREATE POLICY "Allow public update worker_machines" ON public.worker_machines FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public delete worker_machines" ON public.worker_machines;
CREATE POLICY "Allow public delete worker_machines" ON public.worker_machines FOR DELETE TO anon, authenticated USING (true);
