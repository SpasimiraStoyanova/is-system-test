-- ==============================================================================
-- СИСТЕМА ЗА ЕКСПРЕСНИ / ИЗНЕНАДВАЩИ РЕВИЗИИ (SPOT AUDITS)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS public.spot_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    target_machine TEXT NOT NULL,
    target_worker TEXT, -- Персонално насочена към конкретен работник (или NULL за всеки на машината)
    part_code TEXT NOT NULL,
    operation TEXT NOT NULL,
    expected_qty NUMERIC NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'PENDING', -- 'PENDING', 'MATCH', 'DISCREPANCY', 'CANCELLED'
    answered_at TIMESTAMP WITH TIME ZONE,
    worker_name TEXT,
    reported_qty NUMERIC,
    difference_qty NUMERIC DEFAULT 0,
    notes TEXT
);

-- Добавяне на колоната target_worker ако таблицата вече е създадена
ALTER TABLE public.spot_audits ADD COLUMN IF NOT EXISTS target_worker TEXT;

-- Индекси за бързина
CREATE INDEX IF NOT EXISTS idx_spot_audits_machine_status ON public.spot_audits (target_machine, status);
CREATE INDEX IF NOT EXISTS idx_spot_audits_created_at ON public.spot_audits (created_at DESC);

-- Активиране на Realtime
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'spot_audits'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.spot_audits;
    END IF;
EXCEPTION WHEN OTHERS THEN
    -- Игнорираме грешка ако публикацията не съществува в тази конфигурация
    NULL;
END $$;

-- RLS Политики за пълен достъп от клиентските приложения
ALTER TABLE public.spot_audits ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow public read spot_audits" ON public.spot_audits;
CREATE POLICY "Allow public read spot_audits" ON public.spot_audits FOR SELECT TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "Allow public insert spot_audits" ON public.spot_audits;
CREATE POLICY "Allow public insert spot_audits" ON public.spot_audits FOR INSERT TO anon, authenticated WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public update spot_audits" ON public.spot_audits;
CREATE POLICY "Allow public update spot_audits" ON public.spot_audits FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public delete spot_audits" ON public.spot_audits;
CREATE POLICY "Allow public delete spot_audits" ON public.spot_audits FOR DELETE TO anon, authenticated USING (true);

