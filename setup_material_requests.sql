CREATE TABLE IF NOT EXISTS public.material_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL,
    task_id text,
    part_name text NOT NULL,
    op_name text,
    machine text,
    operator text,
    operator_email text,
    reasons text,
    status text DEFAULT 'Чакаща' NOT NULL, -- 'Чакаща', 'Осигурена', 'Отхвърлена'
    resolved_at timestamp with time zone,
    resolved_by text,
    notes text
);

-- RLS Политики за достъп
ALTER TABLE public.material_requests ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all on material_requests" ON public.material_requests;
CREATE POLICY "Allow all on material_requests" ON public.material_requests 
FOR ALL USING (true) WITH CHECK (true);

GRANT ALL ON public.material_requests TO anon, authenticated;

